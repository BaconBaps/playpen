        '+' to "00000/00100/00100/11111/00100/00100/00000",
        '!' to "00100/00100/00100/00100/00100/00000/00100",
        '?' to "01110/10001/00001/00010/00100/00000/00100",
        '>' to "10000/01000/00100/00010/00100/01000/10000",
        '<' to "00001/00010/00100/01000/00100/00010/00001",
        '(' to "00010/00100/01000/01000/01000/00100/00010",
        ')' to "01000/00100/00010/00010/00010/00100/01000",
        '&' to "01100/10010/10100/01000/10101/10010/01101",
        '×' to "00000/10001/01010/00100/01010/10001/00000",
        '·' to "00000/00000/00000/00100/00000/00000/00000",
        '•' to "00000/00000/01110/01110/01110/00000/00000",
        '%' to "11001/11010/00100/00100/01000/10110/00110"
    )
    private val glyphs=mutableMapOf<Char,Bitmap>()
    private val filters=mutableMapOf<Int,ColorFilter>()
    private val paint=Paint().apply { isAntiAlias=false;isFilterBitmap=false;isDither=false }
    private val destination=RectF()
    private fun glyph(c: Char)=glyphs.getOrPut(c) {
        val pixels=IntArray(35)
        (patterns[c] ?: patterns.getValue('?')).split('/').forEachIndexed { y,row ->
            row.forEachIndexed { x,v -> if(v=='1')pixels[y*5+x]=Color.WHITE }
        }
        Bitmap.createBitmap(pixels,5,7,Bitmap.Config.ARGB_8888)
    }
    fun draw(canvas: Canvas,text: String,x: Float,baseline: Float,size: Float,color: Int,maxWidth: Float=352f) {
        val s=text.uppercase(Locale.ROOT).replace('›','>').replace('‹','<').replace('—','-').replace('–','-')
        if(s.isEmpty())return
        val unit=min(size/8f,maxWidth/(s.length*6f)).coerceAtLeast(0.6f)
        paint.colorFilter=filters.getOrPut(color) { LightingColorFilter(0,color) }
        paint.alpha=Color.alpha(color)
        var cursor=x
        for(c in s) {
            if(c!=' ') {
                destination.set(cursor,baseline-unit*7f,cursor+unit*5f,baseline)
                canvas.drawBitmap(glyph(c),null,destination,paint)
            }
            cursor+=unit*6f
        }
        paint.colorFilter=null;paint.alpha=255
    }
}
